/**
 * コイン購入の前に示す説明と、その版。
 *
 * ⚠️ **表示とログを1か所にまとめてある**（`bookingPolicy.ts` と同じ考え方）。
 *
 * 0106 で異議申立ての証跡（`policy_consents`）を作ったとき、
 * kind='purchase' の器だけ用意して**呼び出しを繋いでいなかった**。
 * 2026-08-05 の横断点検（G19）で発覚。画面には「購入手続の完了後は
 * 返金できません」と出ているのに、**見せた事実を残していなかった**ため、
 * チャージバックで「返金不可と知らされていない」と言われたときに反論できない。
 *
 * `admin_purchase_evidence()` は、この文面を Stripe の異議申立てフォームの
 * 「顧客が返金ポリシーに同意したことを示す記録」欄にそのまま貼れる形で返す。
 *
 * **1文字でも変えたら、下の版を上げること。**
 * 上げないと、旧文言で買った人と新文言で買った人が記録上区別できなくなる。
 */
export const PURCHASE_POLICY_VERSION = '2026-08-05'

/**
 * 購入ボタンのすぐ上に出す説明。
 *
 * ここに書くのは、**あとで争いになる論点だけ**に絞る。
 * 長くすると読まれず、「表示していた」という主張の説得力が落ちる。
 *
 * `**…**` は画面で太字になる。ログにはマーカーごと残す
 * （どこを強調して見せたかも記録の一部）。
 */
export const PURCHASE_POLICY_LINES: string[] = [
  'コインは、ピタメイトの時間を予約するために本サービス内でのみ使えます。',
  '**日本円への払い戻し・換金・出金はできません**（利用規約 第7条3項）。',
  'コインの**有効期限は取得日から6か月未満**です。期限を過ぎたコインは消滅します。',
  'あんしんサポート料はコイン価格に加えてお支払いいただく費用で、**コインの残高には加算されません**。',
  '**購入手続の完了後は返金できません**（法令上返金が必要な場合を除きます）。',
]

/** 記録用の1本のテキスト。**画面に出したものと同じ配列から作る。** */
export function purchasePolicyText(): string {
  return (
    `【コインの購入について】(版 ${PURCHASE_POLICY_VERSION})\n` +
    PURCHASE_POLICY_LINES.join('\n')
  )
}

/**
 * 利用登録のときに同意した規約の版。
 *
 * 規約 第3条6項（2026-08-05新設）:
 *   「利用登録の申込みを行う者は、本規約に同意するものとします。
 *    当社は、**同意がなされた日時および同意の対象となった本規約の版を
 *    記録します。**」
 *
 * 弁護士（2026-08-05 論点A(c)2・E(a)）:
 *   「定型約款の組入れ（民法548条の2）自体は表示で足りますが、……
 *    規約本体への同意手続を明記していません。」
 *   管轄合意が「書面（電磁的記録を含む）」で行われたことの立証
 *   （民訴11条2項・3項）にも効く。
 *
 * **規約を改定したら、この値を上げること。**
 */
export const TERMS_CONSENT_VERSION = '2026-08-05'

/**
 * 登録時に同意した対象を1本のテキストにする。
 *
 * ⚠️ **規約の全文は入れない。** 数万字を毎回保存する意味はなく、
 * `policy_consents.shown_text` は 4,000 字で切られる。
 * ここでは「いつの版の、どの文書に同意したか」を残す
 * （全文は `terms-of-service-draft.md` の版で追える）。
 */
export function termsConsentText(): string {
  return (
    `【利用登録時の同意】(規約の版 ${TERMS_CONSENT_VERSION})\n` +
    '次の内容に同意して利用登録を行いました。\n' +
    '・利用規約\n' +
    '・プライバシーポリシー\n' +
    '・役務提供に関するガイドライン（利用規約 第1条2項により規約の一部）'
  )
}
