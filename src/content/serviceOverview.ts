/**
 * ログイン不要の「サービス紹介」ページの中身。
 *
 * ■ なぜ作ったか
 *   個人事業主口座の開設審査で、銀行から
 *   「ホームページの内容では、情報量が少なく『現在、実際に事業活動を行われている
 *    こと』が確認できませんでした」という不備通知を受けた（2026-08-07）。
 *   原因は、pitafure.com を開いた人に見えるのがヒーローと登録ボタンだけで、
 *   **価格もサービスの流れもログインの内側にあった**こと。
 *   通知には「価格、購入方法、サービスの流れなど具体的な内容が記載されていると、
 *   確認がスムーズに行える可能性が高くなります」とある。
 *   `docs/銀行_書類不備の対応.txt` 3(b)。
 *
 * ■ だから、この4つは必ず未ログインで読めること
 *   ① 価格（コインの単価・パック・あんしんサポート料）
 *   ② 購入方法（決済手段）
 *   ③ サービスの流れ
 *   ④ ピタメイト側の手数料
 *   審査の相手はアプリを使ってくれません。**登録しないと分からない、を無くす**
 *   のがこのページの役目です。
 *
 * ■ 数値をここに直書きしないこと
 *   コインのパックは `flow.ts` の `COIN_PACKS`、あんしんサポート料は
 *   `pricing.ts`、手数料の率はサーバの `fee_rates`（`fetchFeeRates`）が権威です。
 *   ここに写すと、料率を変えたときに**このページだけ古い数字を出し続けます**。
 *   価格表示は申込前の表示なので、ずれた瞬間に景表法の問題になります。
 *
 * ■ 書けないこと（sns-launch-kit.md §6 と同じ制約がかかります）
 *   ・「出会い系」は否定の形でも書かない → 「本来の目的以外の利用はできません」
 *   ・「ホスト」と呼ばない → ピタメイト
 *   ・手数料は「20%から」。下限の10%を単独で出さない（§6-2）
 *   ・「無料」は登録だけに限って言い切る（遊ぶにはコインが要る）
 */

